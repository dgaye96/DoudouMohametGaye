const originals = new WeakMap();
const SKIP = new Set(['SCRIPT', 'STYLE', 'NOSCRIPT']);
const normalize = text => text.trim().replace(/\s+/g, ' ');

const lookup = value => {
  if (FR[value] !== undefined) return FR[value];
  const key = normalize(value);
  return FR[key];
};

const contextLookup = (node, value) => {
  const parent = node.parentElement;
  if (!parent) return undefined;
  const key = normalize(value);
  for (const entry of CONTEXT) {
    if (entry.map[key] !== undefined && parent.closest(entry.selector)) return entry.map[key];
  }
  return undefined;
};

const applyTo = (node, toFrench) => {
  if (!originals.has(node)) originals.set(node, node.nodeValue);
  const original = originals.get(node);
  if (!normalize(original)) return;
  if (!toFrench) { node.nodeValue = original; return; }
  const translation = contextLookup(node, original) ?? lookup(original);
  if (translation === undefined) return;
  node.nodeValue = original.replace(normalize(original), translation);
};

const translateAttributes = toFrench => {
  document.querySelectorAll('[aria-label],[alt],[placeholder]').forEach(el => {
    ['aria-label', 'alt', 'placeholder'].forEach(name => {
      const current = el.getAttribute(name);
      if (current === null) return;
      const store = `i18n${name.replace(/-/g, '')}`;
      if (!el.dataset[store]) el.dataset[store] = current;
      const original = el.dataset[store];
      const translation = lookup(original);
      el.setAttribute(name, toFrench && translation !== undefined ? translation : original);
    });
  });
};

const apply = scope => {
  const toFrench = document.documentElement.lang === 'fr';
  const walker = document.createTreeWalker(scope || document.body, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      const parent = node.parentElement;
      if (!parent || SKIP.has(parent.tagName)) return NodeFilter.FILTER_REJECT;
      if (parent.closest('.terminal-body')) return NodeFilter.FILTER_REJECT;
      return NodeFilter.FILTER_ACCEPT;
    }
  });
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  nodes.forEach(node => applyTo(node, toFrench));
  if (scope) return;
  translateAttributes(toFrench);

  if (!document.documentElement.dataset.i18nTitle) {
    document.documentElement.dataset.i18nTitle = document.title;
    const meta = document.querySelector('meta[name="description"]');
    if (meta) document.documentElement.dataset.i18nDesc = meta.content;
  }
  const titleOriginal = document.documentElement.dataset.i18nTitle;
  const titleFr = lookup(titleOriginal);
  document.title = toFrench && titleFr !== undefined ? titleFr : titleOriginal;
  const meta = document.querySelector('meta[name="description"]');
  if (meta && document.documentElement.dataset.i18nDesc) {
    const descOriginal = document.documentElement.dataset.i18nDesc;
    const descFr = lookup(descOriginal);
    meta.content = toFrench && descFr !== undefined ? descFr : descOriginal;
  }
};

window.dmgI18n = {
  get lang() { return document.documentElement.lang; },
  t(text) {
    if (document.documentElement.lang !== 'fr') return text;
    const translation = lookup(text);
    return translation === undefined ? text : translation;
  },
  apply
};

